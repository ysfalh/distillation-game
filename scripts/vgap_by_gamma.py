#!/usr/bin/env python3
"""Do the token-level defenses suppress the teacher-proxy likelihood gap?

The sequence-level rule the defenses are up against scores a trace by

    v_gap(y) = log P_teacher(y) - log P_proxy(y)

and this script measures that quantity directly on traces already generated by
each defense, against the undefended teacher.

PoE samples each token from a blend of the two models,

    q(a|h) proportional to p_teacher(a|h)^(1-gamma) * p_proxy(a|h)^gamma

so it should pull the sampled text toward tokens the proxy also finds likely,
and v_gap should fall as gamma rises. Antidistillation sampling is measured the
same way at each lambda. It perturbs the teacher's logits with a
finite-difference penalty and never consults the proxy, so whatever it does to
v_gap is a side effect; comparing the two families says whether a drop is
attributable to the proxy mixing or to perturbing the traces at all.

v_gap is one number per trace, defined by the equation above. Because the sum
grows with trace length -- on these traces its rank correlation with response
length is +0.88 -- a bare sum would mostly report how long the traces are, and
PoE changes trace length as a side effect. Dividing by the number of response
tokens gives the same per-trace quantity on a per-token scale, comparable across
traces of different lengths, so that is the headline number. The sum is reported
alongside it, and the median per-token gap is reported too, since one trace with
an extreme gap cannot move a median.

Every source covers the identical GSM8K problems in the same order, so each
defense is compared to the undefended baseline *paired by problem*: the
statistic is the mean of v_gap(defended trace) - v_gap(standard trace) over
problems. Pairing cancels problem difficulty, which is the dominant source of
variation in v_gap, and it comes with a distribution-free companion, the
fraction of problems whose gap went down at all. Beyond the average, the report
gives the quantiles of each distribution, whether one sits wholly below the
other, and the largest distance between their CDFs.

Both models score token ids produced by the teacher's tokenizer, which is what
PoE does at generation time, and only response tokens count.

Usage:
    python scripts/vgap_by_gamma.py --seed 123
    python scripts/vgap_by_gamma.py --report-only
"""
